"""Bake the trained LDA parameters in models/<version>/ into a C++ header for the Teensy.

The Teensy has no filesystem, so the firmware can't read the .json/.npy files at runtime.
Rerun this (and reflash) after every retrain:

    cd python && python export_model_header.py
"""
import json
import os

import numpy as np

MODEL_VERSION = "v4"
MODEL_DIR = os.path.join("..", "models", MODEL_VERSION)
HEADER_PATH = os.path.join("..", "firmware", "model_params.h")


def load_model_files(model_dir):
    with open(os.path.join(model_dir, "class_mapping.json")) as f:
        class_mapping = {int(k): v for k, v in json.load(f).items()}
    with open(os.path.join(model_dir, "class_priors.json")) as f:
        priors = json.load(f)
    with open(os.path.join(model_dir, "feature_columns.json")) as f:
        feature_columns = json.load(f)
    covariance = np.load(os.path.join(model_dir, "lda_shared_covariance.npy"))
    return class_mapping, priors, feature_columns, covariance


def fmt(x):
    return repr(float(x))  # shortest repr that round-trips the float64 exactly


def build_header(class_mapping, priors, feature_columns, covariance):
    # priors were saved from lda.priors_, which follows lda.classes_ (sorted labels)
    class_ids = sorted(class_mapping)
    class_names = [class_mapping[c] for c in class_ids]
    num_classes = len(class_ids)
    num_features = len(feature_columns)

    assert len(priors) == num_classes, f"{len(priors)} priors for {num_classes} classes"
    assert covariance.shape == (num_features, num_features), f"covariance shape {covariance.shape}"
    assert "rest" in class_names, "no 'rest' class in class_mapping.json"

    # same inversion pred_realtime.py does, done here so the Teensy doesn't have to
    inv_cov = np.linalg.pinv(covariance)

    lines = [
        f"// AUTO-GENERATED by python/export_model_header.py from models/{MODEL_VERSION} -- do not edit.",
        "// Rerun the script and reflash after retraining.",
        "#pragma once",
        "",
        f"constexpr int MODEL_NUM_CLASSES = {num_classes};",
        f"constexpr int MODEL_NUM_FEATURES = {num_features};",
        f"constexpr int MODEL_REST_INDEX = {class_names.index('rest')};",
        "",
        "// feature order the model was trained on (firmware feature vector must match):",
        "// " + ", ".join(feature_columns),
        "",
        f"constexpr int MODEL_CLASS_IDS[MODEL_NUM_CLASSES] = {{{', '.join(str(c) for c in class_ids)}}};",
        "constexpr const char* MODEL_CLASS_NAMES[MODEL_NUM_CLASSES] = {"
        + ", ".join(f'"{n}"' for n in class_names) + "};",
        f"constexpr double MODEL_PRIORS[MODEL_NUM_CLASSES] = {{{', '.join(fmt(p) for p in priors)}}};",
        "",
        "// pinv(shared covariance), row-major",
        "constexpr double MODEL_INV_COV[MODEL_NUM_FEATURES][MODEL_NUM_FEATURES] = {",
    ]
    for row in inv_cov:
        lines.append("    {" + ", ".join(fmt(v) for v in row) + "},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    header = build_header(*load_model_files(MODEL_DIR))
    with open(HEADER_PATH, "w") as f:
        f.write(header)
    print(f"Wrote {HEADER_PATH}")


if __name__ == "__main__":
    main()
